@spaces.GPU(duration=30)
def run_council_inference(image_input: str | None, modality_override: str):
    if not image_input:
        return (
            "⚠️ **Please upload a medical scan or select one of the examples below.**",
            [],
            [],
            "No analysis performed.",
            "No report generated.",
        )

    override = None
    if modality_override and modality_override != "Auto-detect":
        override = modality_override.lower().strip()

    req = AnalysisRequest(
        file_path=str(image_input),
        modality_override=override,
        enable_explainability=True,
        enable_agent=True,
    )

    try:
        res = pipeline.analyze(req)
    except Exception as e:
        logger.error("Inference failed: %s", e, exc_info=True)
        return (
            f"❌ **Error during analysis:** {str(e)}",
            [],
            [],
            f"Analysis Error: {e}",
            "Report unavailable.",
        )

    cr = res.council_result
    agent = res.agent_insight

    # 1. Consensus Banner (Markdown)
    severity_colors = {
        "clear": "🟢",
        "info": "🔵",
        "warning": "🟠",
        "critical": "🔴",
    }
    sev_icon = severity_colors.get(cr.severity.value, "⚪")

    consensus_md = f"""### {sev_icon} Primary Finding: **{cr.primary_finding}** (Confidence: {cr.primary_finding_confidence:.1%})

| Consensus Level | Agreement Score | Ensemble Uncertainty (Entropy) | Evidence Strength | Clinical Severity |
| :---: | :---: | :---: | :---: | :---: |
| **{cr.consensus_level.value.upper()}** | **{cr.agreement_score:.1%}** ({cr.models_agreeing}/{cr.models_total} models) | **{cr.ensemble_uncertainty:.2f}** | **{cr.evidence_strength.value.upper()}** | **{cr.severity.value.upper()}** |
"""
    if cr.disagreements:
        consensus_md += f"\n⚠️ **Divergence Detected:** {len(cr.disagreements)} model(s) diverged from the majority consensus."

    # 2. Gallery Images: Input Scan + Grad-CAM Heatmaps
    gallery_items: list[tuple[str, str]] = []
    gallery_items.append((str(image_input), "Original Study Scan"))

    for ov in res.overlays:
        if ov.png_path and Path(ov.png_path).exists():
            label = f"{ov.model_id} ({ov.overlay_type.upper()})"
            gallery_items.append((ov.png_path, label))

    # 3. Model Evidence Table
    model_rows = []
    for ev in cr.member_evidence:
        top_prob = ev.probabilities.get(ev.prediction, ev.confidence) if ev.probabilities else ev.confidence
        model_rows.append([
            ev.model_name,
            ev.model_architecture,
            ev.prediction,
            f"{ev.confidence:.1%}",
            f"{ev.uncertainty:.2f}",
            f"{ev.processing_time_ms:.0f} ms",
            ev.status.value.upper(),
        ])

    # 4. Agent Insights
    insights_md = "### 🩺 Agentic Clinical Synthesis\n"
    if agent:
        insights_md += f"*Generated by **{agent.agent_model}** in {agent.processing_time_ms:.0f}ms*\n\n"
        if agent.key_insights:
            insights_md += "**Key Insights:**\n"
            for k in agent.key_insights:
                insights_md += f"- {k}\n"
        if agent.clinical_significance:
            insights_md += "\n**Clinical Significance:**\n"
            for s in agent.clinical_significance:
                insights_md += f"- {s}\n"
        if agent.recommended_actions:
            insights_md += "\n**Recommended Follow-up Actions:**\n"
            for a in agent.recommended_actions:
                insights_md += f"- {a}\n"
        if agent.safety_flags:
            insights_md += "\n**Safety & Review Flags:**\n"
            for sf in agent.safety_flags:
                insights_md += f"- ⚠️ *{sf}*\n"
    else:
        insights_md += "Agent synthesis offline."

    # 5. Full Structured Report
    structured_rep = generate_report(cr, agent)
    report_text = structured_rep.to_text()

    return consensus_md, gallery_items, model_rows, insights_md, report_text


