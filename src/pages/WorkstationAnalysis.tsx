/**
 * CouncilMed — Workstation Analysis Page
 * ==========================================
 * The primary workstation view: image on the left, council evidence on the right.
 * This replaces the separate MRI/CT/XRay pages with a single unified analysis view.
 *
 * Layout: [Image Viewer | Council Evidence Panel]
 * The image/study is the CENTER of the experience.
 */

import { useState, useCallback, useRef, useEffect } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { useNavigate } from 'react-router-dom';
import {
  Upload, FileImage, AlertCircle, ChevronRight,
  RotateCcw, Info,
  Bot, Sparkles, Brain, FileText, X, ExternalLink, Loader2
} from 'lucide-react';
import { HudPanel } from '../components/ui/HudPanel';
import { WorkspaceEnvironment } from '../components/3d/WorkspaceEnvironment';
import { CouncilEvidencePanel } from '../components/council/CouncilEvidencePanel';
import { MedicalImageViewer } from '../components/viewer/MedicalImageViewer';
import { useCouncilAnalysis } from '../hooks/useCouncilAnalysis';
import { api } from '../services/api';
import { ReportViewer } from './Reports';
import type { ReportResponse, ReportSectionResponse, AnalyzeResponse } from '../services/api';

const API_BASE = 'http://localhost:8000';

function synthesizeReportFromResult(result: AnalyzeResponse): ReportResponse {
  const cr = result.council_result;
  const sections: ReportSectionResponse[] = [
    {
      title: 'Study Information',
      content: [
        `Modality: ${result.modality || 'Not specified'}`,
        `Anatomy: ${result.anatomy || 'Not specified'}`,
        `Study ID: ${result.request_id || 'Not available'}`,
        `Analysis Timestamp: ${new Date().toISOString()}`,
      ],
      subsections: [],
      severity: '',
    },
    {
      title: 'AI Council Consensus',
      content: [
        `Primary Finding: ${cr.primary_finding}`,
        `Confidence: ${(cr.primary_finding_confidence * 100).toFixed(1)}%`,
        `Consensus Level: ${cr.consensus_level.toUpperCase()}`,
        `Evidence Strength: ${cr.evidence_strength.toUpperCase()}`,
        `Severity: ${cr.severity.toUpperCase()}`,
        `Models in Agreement: ${cr.models_agreeing}/${cr.models_total}`,
        `Agreement Score: ${(cr.agreement_score * 100).toFixed(1)}%`,
        `Ensemble Uncertainty: ${(cr.ensemble_uncertainty * 100).toFixed(1)}%`,
      ],
      subsections: [],
      severity: cr.severity,
    },
    {
      title: 'Individual Model Evidence',
      content: [],
      subsections: cr.member_evidence.map(ev => ({
        title: `${ev.model_name} (v${ev.model_version})`,
        content: [
          `Architecture: ${ev.model_architecture}`,
          `Prediction: ${ev.prediction}`,
          `Confidence: ${(ev.confidence * 100).toFixed(1)}%`,
          `Uncertainty: ${(ev.uncertainty * 100).toFixed(1)}%`,
          `Processing Time: ${ev.processing_time_ms.toFixed(0)}ms`,
          `Device: ${ev.device || 'cpu'}`,
          ...(ev.probabilities ? Object.entries(ev.probabilities).map(([k, v]) => `  ${k}: ${(v * 100).toFixed(1)}%`) : [])
        ],
        subsections: [],
        severity: '',
      })),
      severity: '',
    }
  ];

  if (result.agent_insight && result.agent_insight.key_insights.length > 0) {
    sections.push({
      title: 'AI Agent Clinical Insights',
      content: [
        ...result.agent_insight.key_insights,
        ...result.agent_insight.clinical_significance.map(s => `Significance: ${s}`),
      ],
      subsections: [],
      severity: '',
    });
  }

  return {
    report_id: `rep-${result.request_id.slice(0, 8)}`,
    version: 1,
    study_type: `${result.modality} ${result.anatomy}`,
    modality: result.modality,
    anatomy: result.anatomy,
    study_date: new Date().toISOString().split('T')[0],
    sections,
    impression: `${cr.primary_finding} (Confidence: ${(cr.primary_finding_confidence * 100).toFixed(1)}%, Consensus: ${cr.consensus_level.toUpperCase()}).`,
    recommendations: cr.requires_human_review ? [
      'Radiologist correlation recommended prior to clinical action.',
      ...cr.human_review_reasons,
    ] : ['Standard follow-up as indicated.'],
    limitations: [
      'This report is generated by AI Council consensus for decision support only.',
      'Must be verified by a licensed radiologist or attending physician.',
    ],
    generated_at: new Date().toISOString(),
    report_status: 'draft',
    report_text: `COUNCILMED CLINICAL REPORT\nStudy: ${result.modality} ${result.anatomy}\nPrimary Finding: ${cr.primary_finding}\nConfidence: ${(cr.primary_finding_confidence * 100).toFixed(1)}%\nConsensus: ${cr.consensus_level}\nModels Agreeing: ${cr.models_agreeing}/${cr.models_total}\n`
  };
}

export default function WorkstationAnalysis() {
  const analysis = useCouncilAnalysis();
  const navigate = useNavigate();
  const [imagePreview, setImagePreview] = useState<string | null>(null);
  const [fileName, setFileName] = useState<string>('');
  
  const [showAgent, setShowAgent] = useState(false);
  const [selectedModality, setSelectedModality] = useState<string>('Brain MRI');
  const [reviewStatus, setReviewStatus] = useState<'accepted' | 'rejected' | 'modified' | null>(null);
  const [showReportModal, setShowReportModal] = useState(false);
  const [reportLoading, setReportLoading] = useState(false);
  const [reportData, setReportData] = useState<ReportResponse | null>(null);
  const [reportError, setReportError] = useState<string | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);
  const previewUrlRef = useRef<string | null>(null);

  const setPreviewFromFile = useCallback((file: File) => {
    if (previewUrlRef.current) {
      URL.revokeObjectURL(previewUrlRef.current);
      previewUrlRef.current = null;
    }

    const ext = file.name.split('.').pop()?.toLowerCase();
    if (['jpg', 'jpeg', 'png', 'bmp', 'tiff', 'webp'].includes(ext || '')) {
      const objectUrl = URL.createObjectURL(file);
      previewUrlRef.current = objectUrl;
      setImagePreview(objectUrl);
    } else {
      setImagePreview(null);
    }
  }, []);

  useEffect(() => () => {
    if (previewUrlRef.current) {
      URL.revokeObjectURL(previewUrlRef.current);
    }
  }, []);

  const parseModality = useCallback((label: string) => {
    const parts = label.split(' ');
    const anatomy = parts[0].toLowerCase();
    const modality = parts.slice(1).join('').replace('-', '');
    return { anatomy, modality };
  }, []);

  const processFile = useCallback(async (file: File) => {
    setFileName(file.name);
    setPreviewFromFile(file);
    setReviewStatus(null);
    setReportData(null);
    setShowReportModal(false);
    setReportError(null);

    const { anatomy, modality } = parseModality(selectedModality);
    const result = await analysis.analyzeFile(file, { modality, anatomy });
    
    // Once analysis completes, use the backend-generated preview if available.
    // This covers DICOM/NIfTI files that can't be displayed as ObjectURLs.
    if (result?.media?.preview_url) {
      if (previewUrlRef.current) {
        URL.revokeObjectURL(previewUrlRef.current);
        previewUrlRef.current = null;
      }
      setImagePreview(`${API_BASE}${result.media.preview_url}`);
    }
  }, [analysis, parseModality, selectedModality, setPreviewFromFile]);

  const handleFileSelect = useCallback(async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    if (fileInputRef.current) fileInputRef.current.value = '';
    await processFile(file);
  }, [processFile]);

  const handleDrop = useCallback(async (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();

    const file = e.dataTransfer.files[0];
    if (!file) return;

    await processFile(file);
  }, [processFile]);

  const handleNewImage = useCallback(() => {
    analysis.reset();
    setFileName('');
    if (previewUrlRef.current) {
      URL.revokeObjectURL(previewUrlRef.current);
      previewUrlRef.current = null;
    }
    setImagePreview(null);
    setReviewStatus(null);
    fileInputRef.current?.click();
  }, [analysis]);

  const handleDragOver = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
  }, []);

  const handleReview = useCallback(async (decision: 'accepted' | 'rejected' | 'modified') => {
    if (!analysis.result) return;
    try {
      await api.submitReview({
        analysis_id: analysis.result.request_id,
        decision,
        reviewer_name: 'Clinician',
      });
      setReviewStatus(decision);
    } catch (err) {
      console.error('Review submission failed:', err);
    }
  }, [analysis.result]);

  const coreState = analysis.status === 'analyzing' ? 'processing' : 
                      analysis.status === 'complete' ? 'complete' : 'idle';

  const showViewer = Boolean(imagePreview || fileName || analysis.isProcessing || analysis.result);

  return (
    <div className="h-full flex flex-col relative">
      <WorkspaceEnvironment coreState={coreState} />

      {/* Top bar (Spatial overlay) */}
      <div className="relative z-10 flex items-center justify-between mb-4 pointer-events-none">
        <div>
          <h1 className="text-2xl font-light tracking-[0.2em] text-white text-glow">
            ANALYSIS WORKSTATION
          </h1>
          <p className="text-zinc-500 text-sm mt-0.5">
            {fileName
              ? `Analyzing: ${fileName}`
              : 'Drop a medical image to begin council analysis'}
          </p>
        </div>

        {analysis.isComplete && analysis.result && (
          <div className="flex items-center gap-2">
            <span className="text-xs text-zinc-500">
              {analysis.result.total_time_ms.toFixed(0)}ms total
            </span>
            <span className="text-xs text-zinc-600">•</span>
            <span className="text-xs text-zinc-500">
              {analysis.result.modality} / {analysis.result.anatomy}
            </span>
          </div>
        )}
      </div>

      {/* Main workspace: Image | Evidence */}
      <div className="relative z-10 flex-1 grid grid-cols-1 lg:grid-cols-5 gap-6 min-h-0">

        {/* Left: Image Viewer (3/5 width) */}
        <div className="lg:col-span-3 flex flex-col min-h-0">
          {!showViewer ? (
            /* Upload Drop Zone */
            <HudPanel
              className="flex-1 flex flex-col items-center justify-center cursor-pointer min-h-[400px]
                border-dashed border-2 hover:border-cyan-500/80 transition-all duration-500 group"
              onDrop={handleDrop}
              onDragOver={handleDragOver}
              onClick={() => fileInputRef.current?.click()}
            >
              <input
                ref={fileInputRef}
                type="file"
                accept=".dcm,.dicom,.nii,.gz,.jpg,.jpeg,.png,.bmp,.tiff"
                className="hidden"
                onChange={handleFileSelect}
              />
              
              {/* Modality Selector (Click stops propagation so it doesn't trigger file dialog) */}
              <div 
                className="absolute top-6 flex items-center justify-center w-full z-10"
                onClick={e => e.stopPropagation()}
              >
                <div className="bg-black/50 backdrop-blur-md border border-white/10 p-1 rounded-xl flex gap-1 shadow-2xl">
                  {['Brain MRI', 'Chest CT', 'Chest X-Ray'].map(mod => (
                    <button
                      key={mod}
                      onClick={() => setSelectedModality(mod)}
                      className={`px-4 py-1.5 rounded-lg text-xs font-medium transition-all ${
                        selectedModality === mod
                          ? 'bg-cyan-500/20 text-cyan-400 border border-cyan-500/30'
                          : 'text-zinc-400 hover:text-white hover:bg-white/5 border border-transparent'
                      }`}
                    >
                      {mod}
                    </button>
                  ))}
                </div>
              </div>

              <motion.div
                initial={{ scale: 0.9, opacity: 0 }}
                animate={{ scale: 1, opacity: 1 }}
                className="flex flex-col items-center pointer-events-none"
              >
                <div className="w-24 h-24 rounded-full bg-cyan-500/10 
                  flex items-center justify-center mb-6 border border-cyan-500/30 group-hover:scale-110 transition-transform duration-700 shadow-[0_0_30px_rgba(0,240,255,0.2)]">
                  <Upload className="w-10 h-10 text-cyan-400" />
                </div>
                <p className="text-xl font-light tracking-widest text-white mb-2 uppercase text-glow">Drop Data Target</p>
                <p className="text-sm text-zinc-500 text-center max-w-sm">
                  DICOM (.dcm), NIfTI (.nii), JPEG, PNG supported.<br />
                  The AI Council will analyze the image with {' '}
                  <span className="text-cyan-400">multiple independent models</span>.
                </p>
                <div className="flex items-center gap-4 mt-6 text-[11px] text-zinc-600">
                  <span className="flex items-center gap-1"><FileImage className="w-3 h-3" /> DICOM</span>
                  <span className="flex items-center gap-1"><FileImage className="w-3 h-3" /> NIfTI</span>
                  <span className="flex items-center gap-1"><FileImage className="w-3 h-3" /> JPEG/PNG</span>
                </div>
              </motion.div>
            </HudPanel>
          ) : (
            /* Medical Image Viewer */
            <div className="flex-1 flex flex-col min-h-[400px] relative">
              {/* Processing overlay */}
              {analysis.isProcessing && (
                <div className="absolute inset-0 flex flex-col items-center justify-center z-30 bg-black/50 backdrop-blur-sm rounded-xl cinematic-border pointer-events-none">
                  <div className="w-16 h-16 border-t-2 border-cyan-500 rounded-full animate-spin mb-6" />
                  
                  <div className="h-8 overflow-hidden mb-2">
                    <AnimatePresence mode="wait">
                      <motion.p
                        key={analysis.status === 'uploading' ? 'INGESTING DATA' : 
                             analysis.progress < 30 ? 'NORMALIZING' : 
                             analysis.progress < 60 ? 'ANALYZING ENTITIES' : 
                             analysis.progress < 90 ? 'BUILDING RELATIONSHIPS' : 'GENERATING INSIGHTS'}
                        initial={{ y: 20, opacity: 0 }}
                        animate={{ y: 0, opacity: 1 }}
                        exit={{ y: -20, opacity: 0 }}
                        className="text-sm font-mono tracking-widest text-cyan-400 uppercase text-glow"
                      >
                        {analysis.status === 'uploading' ? 'INGESTING DATA' : 
                         analysis.progress < 30 ? 'NORMALIZING' : 
                         analysis.progress < 60 ? 'ANALYZING ENTITIES' : 
                         analysis.progress < 90 ? 'BUILDING RELATIONSHIPS' : 'GENERATING INSIGHTS'}
                      </motion.p>
                    </AnimatePresence>
                  </div>
                  
                  <div className="w-64 h-1 rounded-full bg-cyan-900/30 overflow-hidden relative">
                    <div className="absolute inset-0 bg-[url('/scanline.png')] opacity-50" />
                    <motion.div
                      className="h-full bg-cyan-400 shadow-[0_0_10px_rgba(0,240,255,0.8)]"
                      style={{ width: `${analysis.progress}%` }}
                      transition={{ duration: 0.3 }}
                    />
                  </div>
                  <p className="text-[10px] font-mono tracking-widest text-cyan-500/60 mt-4">SYS.PROGRESS: {analysis.progress.toFixed(0)}%</p>
                </div>
              )}

              {/* New Image button */}
              <div className="absolute top-2 right-2 z-20">
                <button
                  onClick={handleNewImage}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium
                    bg-black/60 text-zinc-400 hover:bg-black/80 hover:text-white transition-all backdrop-blur-sm"
                >
                  <Upload className="w-3.5 h-3.5" /> New Image
                </button>
                <input
                  ref={fileInputRef}
                  type="file"
                  accept=".dcm,.dicom,.nii,.gz,.jpg,.jpeg,.png,.bmp,.tiff"
                  className="hidden"
                  onChange={handleFileSelect}
                />
              </div>

              <HudPanel className="flex-1 flex flex-col p-0 overflow-hidden">
                <MedicalImageViewer imageUrl={imagePreview}
                  fileName={fileName}
                  modality={analysis.result?.modality ?? selectedModality.split(' ').slice(1).join(' ')}
                  anatomy={analysis.result?.anatomy ?? selectedModality.split(' ')[0]}
                  imageShape={analysis.result?.image_shape}
                  metadata={analysis.result ? {
                    'Modality': analysis.result.modality,
                    'Anatomy': analysis.result.anatomy,
                    'Image Shape': analysis.result.image_shape.join(' × '),
                    'Device': (analysis.result.hardware?.device as string) || 'cpu',
                    'Total Time': `${analysis.result.total_time_ms.toFixed(0)}ms`,
                    'Models Used': `${analysis.result.council_result.models_total}`,
                  } : undefined}
                  boxes={analysis.result?.council_result.member_evidence
                    ?.map(e => e.bounding_box)
                    .filter((b): b is NonNullable<typeof b> => b != null)
                  }
                  overlays={analysis.result?.media?.overlays?.map(ov => ({
                    ...ov,
                    url: `${API_BASE}${ov.url}`,
                  }))}
                  className="flex-1"
                />
              </HudPanel>
            </div>
          )}
        </div>

        {/* Right: Council Evidence Panel (2/5 width) */}
        <div className="lg:col-span-2 flex flex-col min-h-0 overflow-y-auto z-20">
          {analysis.isError && (
            <HudPanel className="border-red-500/50 bg-red-500/10 mb-4">
              <div className="flex items-start gap-3">
                <AlertCircle className="w-5 h-5 text-red-400 flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-sm font-mono tracking-widest text-red-400 text-glow-red uppercase">Analysis Failed</p>
                  <p className="text-xs text-red-300 mt-2 font-mono">{analysis.error}</p>
                  <button
                    onClick={analysis.reset}
                    className="mt-4 flex items-center gap-2 px-4 py-2 border border-red-500/30 rounded-lg text-xs font-mono tracking-widest
                      bg-black/40 text-red-400 hover:bg-red-500/20 hover:text-white transition-all"
                  >
                    <RotateCcw className="w-3.5 h-3.5" /> RE-INITIALIZE
                  </button>
                </div>
              </div>
            </HudPanel>
          )}

          {analysis.isComplete && analysis.result && (
            <>
              {/* Warnings */}
              {analysis.result.warnings.length > 0 && (
                <HudPanel className="border-amber-500/30 mb-4 bg-amber-500/5">
                  {analysis.result.warnings.map((w, i) => (
                    <p key={i} className="text-xs font-mono text-amber-400 flex items-start gap-2 mb-1">
                      <Info className="w-3.5 h-3.5 mt-0.5 flex-shrink-0" />
                      {w}
                    </p>
                  ))}
                </HudPanel>
              )}

              <CouncilEvidencePanel
                result={analysis.result.council_result}
                onReview={handleReview}
                reviewStatus={reviewStatus}
              />

              {/* View Report Button */}
              <motion.div
                initial={{ opacity: 0, y: 20 }}
                animate={{ opacity: 1, y: 0 }}
                className="mt-4 flex items-center gap-2"
              >
                <button
                  onClick={async () => {
                    if (!analysis.result) return;
                    setShowReportModal(true);
                    setReportError(null);
                    if (!reportData) {
                      setReportLoading(true);
                      try {
                        const rep = await api.generateReport({ analysis_id: analysis.result.request_id });
                        setReportData(rep);
                      } catch (err) {
                        console.warn('API report generation failed, using local council synthesis fallback:', err);
                        setReportData(synthesizeReportFromResult(analysis.result));
                      } finally {
                        setReportLoading(false);
                      }
                    }
                  }}
                  className="flex-1 flex items-center justify-center gap-2 py-3 rounded-lg border border-cyan-500/30 bg-cyan-500/10 text-cyan-400 font-mono tracking-widest text-xs uppercase hover:bg-cyan-500/20 transition-all hover:shadow-[0_0_20px_rgba(0,240,255,0.2)]"
                >
                  <FileText className="w-4 h-4" /> View Generated Report
                </button>
                <button
                  onClick={() => navigate(`/reports?analysis_id=${analysis.result?.request_id}`)}
                  title="Open in Full Reports Hub"
                  className="p-3 rounded-lg border border-cyan-500/30 bg-black/40 text-cyan-400 hover:bg-cyan-500/20 hover:text-white transition-all shadow-[0_0_15px_rgba(0,240,255,0.1)]"
                >
                  <ExternalLink className="w-4 h-4" />
                </button>
              </motion.div>

              {/* Agent Insight (if available) */}
              {analysis.result.agent_insight && (
                <motion.div
                  initial={{ opacity: 0, y: 20 }}
                  animate={{ opacity: 1, y: 0 }}
                  className="mt-4"
                >
                  <button
                    onClick={() => setShowAgent(!showAgent)}
                    className="flex items-center gap-2 w-full text-left mb-2"
                  >
                    <Bot className="w-4 h-4 text-purple-400" />
                    <span className="text-[11px] text-zinc-500 uppercase tracking-wider">
                      AI Agent Insights
                    </span>
                    <ChevronRight className={`w-3 h-3 text-zinc-600 transition-transform ${showAgent ? 'rotate-90' : ''}`} />
                  </button>

                  <AnimatePresence>
                    {showAgent && (
                      <motion.div
                        initial={{ height: 0, opacity: 0 }}
                        animate={{ height: 'auto', opacity: 1 }}
                        exit={{ height: 0, opacity: 0 }}
                        className="overflow-hidden"
                      >
                        <HudPanel className="border-purple-500/30 mt-2">
                          <div className="space-y-4">
                            {analysis.result.agent_insight.key_insights.length > 0 && (
                              <div>
                                <p className="text-[10px] font-mono text-purple-400 uppercase tracking-widest mb-2 border-b border-purple-500/20 pb-1">Key Insights</p>
                                {analysis.result.agent_insight.key_insights.map((insight, i) => (
                                  <p key={i} className="text-xs font-mono text-zinc-300 mb-2 flex items-start gap-2">
                                    <Sparkles className="w-3 h-3 text-purple-400 mt-0.5 flex-shrink-0" />
                                    {insight}
                                  </p>
                                ))}
                              </div>
                            )}

                            {analysis.result.agent_insight.safety_flags.length > 0 && (
                              <div>
                                <p className="text-[10px] font-mono text-red-400 uppercase tracking-widest mb-2 border-b border-red-500/20 pb-1">Safety Flags</p>
                                {analysis.result.agent_insight.safety_flags.map((flag, i) => (
                                  <p key={i} className="text-xs font-mono text-red-300 mb-2 flex items-start gap-2">
                                    <AlertCircle className="w-3 h-3 text-red-400 mt-0.5 flex-shrink-0" />
                                    {flag}
                                  </p>
                                ))}
                              </div>
                            )}

                            {analysis.result.agent_insight.recommended_actions.length > 0 && (
                              <div>
                                <p className="text-[10px] font-mono text-cyan-400 uppercase tracking-widest mb-2 border-b border-cyan-500/20 pb-1">Recommended Actions</p>
                                {analysis.result.agent_insight.recommended_actions.map((action, i) => (
                                  <p key={i} className="text-xs font-mono text-zinc-300 mb-2 flex items-start gap-2">
                                    <ChevronRight className="w-3 h-3 text-cyan-400 mt-0.5 flex-shrink-0" />
                                    {action}
                                  </p>
                                ))}
                              </div>
                            )}

                            <div className="pt-3 flex items-center justify-between text-[10px] font-mono text-cyan-500/50 uppercase tracking-widest">
                              <span>MODEL: {analysis.result.agent_insight.agent_model}</span>
                              <span>LATENCY: {analysis.result.agent_insight.processing_time_ms.toFixed(0)}ms</span>
                            </div>
                          </div>
                        </HudPanel>
                      </motion.div>
                    )}
                  </AnimatePresence>
                </motion.div>
              )}
            </>
          )}

          {/* Idle state: instructions */}
          {analysis.status === 'idle' && (
            <HudPanel className="flex-1 flex flex-col items-center justify-center text-center opacity-70">
              <Brain className="w-12 h-12 text-cyan-500/40 mb-6 drop-shadow-[0_0_15px_rgba(0,240,255,0.3)]" />
              <p className="text-sm font-mono tracking-widest text-white mb-3 text-glow uppercase">Council Evidence Stream</p>
              <p className="text-xs font-mono text-zinc-400 max-w-xs leading-relaxed">
                System awaiting data ingest. Provide medical imagery to initialize the multi-model intelligence consensus protocol.
              </p>
            </HudPanel>
          )}
        </div>
      </div>

      {/* Report Modal */}
      <AnimatePresence>
        {showReportModal && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6 md:p-10 bg-black/80 backdrop-blur-md">
            <motion.div
              initial={{ opacity: 0, scale: 0.95, y: 20 }}
              animate={{ opacity: 1, scale: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.95, y: 20 }}
              className="relative w-full max-w-4xl max-h-[90vh] flex flex-col bg-zinc-950 border border-cyan-500/30 rounded-2xl shadow-[0_0_50px_rgba(0,240,255,0.15)] overflow-hidden"
            >
              {/* Modal Header */}
              <div className="flex items-center justify-between px-6 py-4 border-b border-white/10 bg-white/[0.02]">
                <div className="flex items-center gap-3">
                  <div className="p-2 rounded-lg bg-cyan-500/10 border border-cyan-500/20 text-cyan-400">
                    <FileText className="w-5 h-5" />
                  </div>
                  <div>
                    <h2 className="text-base font-bold text-white tracking-wide">Clinical Evidence Report</h2>
                    <p className="text-xs text-zinc-400 font-mono">
                      {analysis.result?.modality} • {analysis.result?.anatomy} • ID: {analysis.result?.request_id.slice(0, 8)}
                    </p>
                  </div>
                </div>

                <div className="flex items-center gap-2">
                  <button
                    onClick={() => navigate(`/reports?analysis_id=${analysis.result?.request_id}`)}
                    className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-cyan-500/30 text-cyan-400 text-xs font-mono hover:bg-cyan-500/10 transition-colors"
                  >
                    <ExternalLink className="w-3.5 h-3.5" /> Full Screen
                  </button>
                  <button
                    onClick={() => setShowReportModal(false)}
                    className="p-1.5 rounded-lg text-zinc-400 hover:text-white hover:bg-white/10 transition-colors"
                  >
                    <X className="w-5 h-5" />
                  </button>
                </div>
              </div>

              {/* Modal Body */}
              <div className="flex-1 overflow-y-auto p-6 space-y-4">
                {reportLoading && (
                  <div className="flex flex-col items-center justify-center py-20">
                    <Loader2 className="w-8 h-8 text-cyan-400 animate-spin mb-4" />
                    <p className="text-sm font-mono text-zinc-400">Generating formal clinical report...</p>
                    <p className="text-xs font-mono text-zinc-600 mt-1">Synthesizing evidence from multi-model council</p>
                  </div>
                )}

                {reportError && !reportData && (
                  <div className="p-4 rounded-xl bg-red-500/10 border border-red-500/20 text-red-400 text-sm font-mono flex items-center justify-between">
                    <span>{reportError}</span>
                    <button
                      onClick={async () => {
                        if (!analysis.result) return;
                        setReportLoading(true);
                        setReportError(null);
                        try {
                          const rep = await api.generateReport({ analysis_id: analysis.result.request_id });
                          setReportData(rep);
                        } catch {
                          setReportData(synthesizeReportFromResult(analysis.result));
                        } finally {
                          setReportLoading(false);
                        }
                      }}
                      className="px-3 py-1 bg-red-500/20 rounded text-xs text-white"
                    >
                      Retry
                    </button>
                  </div>
                )}

                {!reportLoading && reportData && (
                  <ReportViewer report={reportData} />
                )}
              </div>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </div>
  );
}




