"""
CouncilMed — Report Generator
=================================
Generates structured radiology-style reports from real council evidence.

This replaces the previous RadiologyReportView.tsx which fabricated report
content using hardcoded strings. Every field in these reports is now derived
from actual model outputs.

Report Structure (aligned with HL7 CDA R2):
  - Patient Demographics (de-identified)
  - Study Information (from DICOM metadata)
  - Findings (from council evidence)
  - Council Consensus (agreement, uncertainty, severity)
  - Per-Model Evidence (individual predictions)
  - Explainability References (Grad-CAM paths)
  - Impression (synthesized finding)
  - Recommendations
  - Limitations (explicitly stated)
"""

from __future__ import annotations

import json
import logging
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ..council.evidence import (
    CouncilResult,
    ModelEvidence,
    ModelStatus,
    AgentInsight,
    ConsensusLevel,
    SeverityLevel,
)

logger = logging.getLogger(__name__)


@dataclass
class ReportSection:
    """A single section of the report."""
    title: str
    content: list[str] = field(default_factory=list)
    subsections: list['ReportSection'] = field(default_factory=list)
    severity: str = ""  # For highlighting


@dataclass
class StructuredReport:
    """Complete structured radiology report."""
    report_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    version: int = 1
    
    # Study info
    study_type: str = ""
    modality: str = ""
    anatomy: str = ""
    study_date: str = ""
    
    # Report content
    sections: list[ReportSection] = field(default_factory=list)
    
    # Summary
    impression: str = ""
    recommendations: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    
    # Metadata
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    report_status: str = "draft"  # draft, final, amended
    
    def to_dict(self) -> dict[str, Any]:
        """Serialize to dictionary for JSON storage."""
        def section_to_dict(s: ReportSection) -> dict:
            return {
                "title": s.title,
                "content": s.content,
                "subsections": [section_to_dict(sub) for sub in s.subsections],
                "severity": s.severity,
            }
        
        return {
            "report_id": self.report_id,
            "version": self.version,
            "study_type": self.study_type,
            "modality": self.modality,
            "anatomy": self.anatomy,
            "study_date": self.study_date,
            "sections": [section_to_dict(s) for s in self.sections],
            "impression": self.impression,
            "recommendations": self.recommendations,
            "limitations": self.limitations,
            "generated_at": self.generated_at,
            "report_status": self.report_status,
        }
    
    def to_text(self) -> str:
        """Render as plain text report."""
        lines: list[str] = []
        lines.append("=" * 60)
        lines.append("COUNCILMED AI-ASSISTED ANALYSIS REPORT")
        lines.append("=" * 60)
        lines.append(f"Report ID: {self.report_id}")
        lines.append(f"Generated: {self.generated_at}")
        lines.append(f"Status: {self.report_status.upper()}")
        lines.append(f"Study: {self.modality} / {self.anatomy}")
        if self.study_date:
            lines.append(f"Study Date: {self.study_date}")
        lines.append("")
        
        for section in self.sections:
            lines.append("-" * 40)
            lines.append(section.title.upper())
            lines.append("-" * 40)
            for line in section.content:
                lines.append(f"  {line}")
            for sub in section.subsections:
                lines.append(f"\n  {sub.title}")
                for line in sub.content:
                    lines.append(f"    {line}")
            lines.append("")
        
        lines.append("=" * 60)
        lines.append("IMPRESSION")
        lines.append("=" * 60)
        lines.append(self.impression)
        lines.append("")
        
        if self.recommendations:
            lines.append("RECOMMENDATIONS:")
            for rec in self.recommendations:
                lines.append(f"  • {rec}")
            lines.append("")
        
        if self.limitations:
            lines.append("LIMITATIONS:")
            for lim in self.limitations:
                lines.append(f"  • {lim}")
            lines.append("")
        
        lines.append("-" * 60)
        lines.append("DISCLAIMER: This report is generated by AI and is intended")
        lines.append("to assist clinical decision-making. It does NOT constitute")
        lines.append("a diagnosis and MUST be reviewed by a qualified clinician.")
        lines.append("-" * 60)
        
        return "\n".join(lines)


def generate_report(
    council_result: CouncilResult,
    agent_insight: AgentInsight | None = None,
    study_date: str = "",
) -> StructuredReport:
    """
    Generate a structured report from real council evidence.
    
    Every field in this report is derived from actual model outputs —
    no fabricated content.
    """
    report = StructuredReport(
        study_type=f"{council_result.modality or 'Unknown'} {council_result.anatomy or 'Unknown'}",
        modality=council_result.modality or "Unknown",
        anatomy=council_result.anatomy or "Unknown",
        study_date=study_date,
    )
    
    # Section 1: Study Information
    study_section = ReportSection(
        title="Study Information",
        content=[
            f"Modality: {council_result.modality or 'Not specified'}",
            f"Anatomy: {council_result.anatomy or 'Not specified'}",
            f"Study ID: {council_result.study_id or 'Not available'}",
            f"Analysis Timestamp: {council_result.timestamp}",
        ],
    )
    report.sections.append(study_section)
    
    # Section 2: Council Consensus
    consensus_section = ReportSection(
        title="AI Council Consensus",
        content=[
            f"Primary Finding: {council_result.primary_finding}",
            f"Confidence: {council_result.primary_finding_confidence:.1%}",
            f"Consensus Level: {council_result.consensus_level.value.upper()}",
            f"Evidence Strength: {council_result.evidence_strength.value.upper()}",
            f"Severity: {council_result.severity.value.upper()}",
            f"Models in Agreement: {council_result.models_agreeing}/{council_result.models_total}",
            f"Agreement Score: {council_result.agreement_score:.1%}",
            f"Ensemble Uncertainty: {council_result.ensemble_uncertainty:.1%}",
        ],
        severity=council_result.severity.value,
    )
    report.sections.append(consensus_section)
    
    # Section 3: Individual Model Evidence
    evidence_section = ReportSection(
        title="Individual Model Evidence",
    )
    
    for ev in council_result.member_evidence:
        if ev.status == ModelStatus.SUCCESS:
            model_sub = ReportSection(
                title=f"{ev.model_name} (v{ev.model_version})",
                content=[
                    f"Architecture: {ev.model_architecture}",
                    f"Prediction: {ev.prediction}",
                    f"Confidence: {ev.confidence:.1%}",
                    f"Uncertainty: {ev.uncertainty:.1%}",
                    f"Processing Time: {ev.processing_time_ms:.0f}ms",
                    f"Device: {ev.device}",
                ],
            )
            
            # Add probability distribution
            if ev.probabilities:
                sorted_probs = sorted(
                    ev.probabilities.items(), key=lambda x: -x[1]
                )
                prob_lines = [f"  {cls}: {prob:.1%}" for cls, prob in sorted_probs]
                model_sub.content.append("Probability Distribution:")
                model_sub.content.extend(prob_lines)
            
            evidence_section.subsections.append(model_sub)
        else:
            evidence_section.subsections.append(ReportSection(
                title=f"{ev.model_name} (v{ev.model_version})",
                content=[
                    f"Status: {ev.status.value}",
                    f"Error: {ev.error_message or 'Unknown error'}",
                ],
            ))
    
    report.sections.append(evidence_section)
    
    # Section 4: Disagreements
    if council_result.disagreements:
        disagreement_section = ReportSection(
            title="Model Disagreements",
            severity="warning",
        )
        for d in council_result.disagreements:
            disagreement_section.content.append(
                f"• {d['model_id']} predicts '{d['model_prediction']}' "
                f"(confidence: {d['model_confidence']:.1%}) — "
                f"disagrees with majority '{d['majority_prediction']}'"
            )
        report.sections.append(disagreement_section)
    
    # Section 5: Human Review Requirements
    review_section = ReportSection(
        title="Review Requirements",
        content=[
            f"Human Review Required: {'Yes' if council_result.requires_human_review else 'No'}",
        ],
    )
    if council_result.human_review_reasons:
        review_section.content.append("Reasons:")
        for reason in council_result.human_review_reasons:
            review_section.content.append(f"  • {reason}")
    report.sections.append(review_section)
    
    # Section 6: Agent Insights (if available)
    if agent_insight and agent_insight.key_insights:
        agent_section = ReportSection(
            title="AI Agent Analysis",
            content=[f"Agent Model: {agent_insight.agent_model}"],
        )
        
        if agent_insight.key_insights:
            agent_section.subsections.append(ReportSection(
                title="Key Insights",
                content=[f"• {i}" for i in agent_insight.key_insights],
            ))
        
        if agent_insight.clinical_significance:
            agent_section.subsections.append(ReportSection(
                title="Clinical Significance",
                content=[f"• {s}" for s in agent_insight.clinical_significance],
            ))
        
        if agent_insight.safety_flags:
            agent_section.subsections.append(ReportSection(
                title="Safety Flags",
                content=[f"⚠ {f}" for f in agent_insight.safety_flags],
                severity="warning",
            ))
        
        report.sections.append(agent_section)
    
    # Impression
    report.impression = _generate_impression(council_result)
    
    # Recommendations
    report.recommendations = _generate_recommendations(council_result, agent_insight)
    
    # Limitations
    report.limitations = _generate_limitations(council_result)
    
    logger.info("Report generated: %s", report.report_id)
    
    return report


def _generate_impression(result: CouncilResult) -> str:
    """Generate the impression summary from council evidence."""
    parts = []
    
    # Qualifier based on consensus
    qualifier_map = {
        ConsensusLevel.STRONG: "with strong inter-model agreement",
        ConsensusLevel.MODERATE: "with moderate inter-model agreement",
        ConsensusLevel.WEAK: "with weak inter-model agreement — interpret with caution",
        ConsensusLevel.NO_CONSENSUS: "without model consensus — findings are inconclusive",
        ConsensusLevel.INSUFFICIENT: "with insufficient data for consensus",
    }
    
    qualifier = qualifier_map.get(result.consensus_level, "")
    
    if result.severity == SeverityLevel.CLEAR:
        parts.append(
            f"AI council analysis ({result.models_total} models) is "
            f"suggestive of {result.primary_finding} "
            f"(confidence: {result.primary_finding_confidence:.1%}), {qualifier}."
        )
    elif result.severity == SeverityLevel.CRITICAL:
        parts.append(
            f"AI council analysis ({result.models_total} models) identifies findings "
            f"suggestive of {result.primary_finding} "
            f"(confidence: {result.primary_finding_confidence:.1%}), {qualifier}. "
            f"Clinical correlation and further evaluation recommended."
        )
    else:
        parts.append(
            f"AI council analysis ({result.models_total} models) suggests "
            f"{result.primary_finding} "
            f"(confidence: {result.primary_finding_confidence:.1%}), {qualifier}."
        )
    
    if result.ensemble_uncertainty > 0.5:
        parts.append(
            f"Note: Ensemble uncertainty is elevated ({result.ensemble_uncertainty:.1%}), "
            "suggesting the models have low agreement on this case."
        )
    
    return " ".join(parts)


def _generate_recommendations(
    result: CouncilResult,
    agent_insight: AgentInsight | None = None,
) -> list[str]:
    """Generate recommendations from council evidence."""
    recs: list[str] = []
    
    # Always recommend clinician review
    recs.append("Clinical correlation with patient history and symptoms is essential.")
    
    if result.severity == SeverityLevel.CRITICAL:
        recs.append("Findings suggest a significant abnormality — consider urgent clinical evaluation.")
    
    if result.consensus_level in (ConsensusLevel.WEAK, ConsensusLevel.NO_CONSENSUS):
        recs.append(
            "Model consensus is low — consider additional imaging or follow-up study "
            "before acting on AI findings."
        )
    
    if result.ensemble_uncertainty > 0.5:
        recs.append(
            "High ensemble uncertainty may indicate this case is unusual or at the boundary "
            "of the training distribution. Exercise additional caution."
        )
    
    # Include agent recommendations if available
    if agent_insight and agent_insight.recommended_actions:
        for action in agent_insight.recommended_actions[:3]:
            if action not in recs:
                recs.append(action)
    
    recs.append("This AI analysis is supplementary and does not replace clinical judgment.")
    
    return recs


def _generate_limitations(result: CouncilResult) -> list[str]:
    """Explicitly state the limitations of this analysis."""
    limitations: list[str] = [
        "AI analysis is limited to the image data provided and does not incorporate clinical history.",
    ]
    
    failed_models = [
        ev for ev in result.member_evidence
        if ev.status != ModelStatus.SUCCESS
    ]
    if failed_models:
        names = [ev.model_name for ev in failed_models]
        limitations.append(
            f"The following models failed to produce evidence: {', '.join(names)}. "
            "This reduces the council's ability to assess agreement."
        )
    
    if result.models_total < 3:
        limitations.append(
            f"Only {result.models_total} model(s) were available for this analysis. "
            "A minimum of 3 independent models is recommended for robust consensus."
        )
    
    limitations.append(
        "Model performance is validated on specific datasets and may not generalize "
        "to all patient populations or imaging protocols."
    )
    
    return limitations
